def validate_restored_fixture(cursor: Cursor[Any], schema: str, migration_head: str) -> None:
    """Fail if the restored data lost core rows or tenant-scoped relationships."""

    for table, expected_count in EXPECTED_COUNTS.items():
        actual = _scalar(cursor, f"SELECT count(*) FROM {_qualified(schema, table)}")
        if actual != expected_count:
            raise RuntimeError(f"{table} restored {actual} rows; expected {expected_count}")

    restored_head = _scalar(
        cursor,
        f"SELECT version_num FROM {_qualified(schema, 'alembic_version')}",
    )
    if restored_head != migration_head:
        raise RuntimeError(f"Restored migration head {restored_head!r} != {migration_head!r}")

    tenant_totals = {
        store_id: total
        for store_id, total in cursor.execute(
            f"""
            SELECT store_id, total_numeric::text
            FROM {_qualified(schema, "orders")}
            ORDER BY store_id
            """
        ).fetchall()
    }
    if tenant_totals != EXPECTED_TENANT_TOTALS:
        raise RuntimeError(f"Restored order totals mismatch: {tenant_totals}")

    cross_tenant_checks = {
        "store/customer": f"""
            SELECT count(*)
            FROM {_qualified(schema, "orders")} orders
            JOIN {_qualified(schema, "customers")} customers
                ON customers.id = orders.customer_id
            WHERE customers.store_id != orders.store_id
        """,
        "order/product": f"""
            SELECT count(*)
            FROM {_qualified(schema, "order_items")} order_items
            JOIN {_qualified(schema, "orders")} orders
                ON orders.id = order_items.order_id
            JOIN {_qualified(schema, "products")} products
                ON products.id = order_items.product_pk
            WHERE products.store_id != orders.store_id
        """,
        "order/variant": f"""
            SELECT count(*)
            FROM {_qualified(schema, "order_items")} order_items
            JOIN {_qualified(schema, "orders")} orders
                ON orders.id = order_items.order_id
            LEFT JOIN {_qualified(schema, "product_variants")} variants
                ON variants.id = order_items.variant_pk
            WHERE variants.id IS NOT NULL AND variants.store_id != orders.store_id
        """,
        "inventory/product": f"""
            SELECT count(*)
            FROM {_qualified(schema, "inventory_transactions")} inventory
            JOIN {_qualified(schema, "products")} products
                ON products.id = inventory.product_pk
            WHERE products.store_id != inventory.store_id
        """,
        "inventory/variant": f"""
            SELECT count(*)
            FROM {_qualified(schema, "inventory_transactions")} inventory
            LEFT JOIN {_qualified(schema, "product_variants")} variants
                ON variants.id = inventory.variant_pk
            WHERE variants.id IS NOT NULL AND variants.store_id != inventory.store_id
        """,
        "membership/store": f"""
            SELECT count(*)
            FROM {_qualified(schema, "stores")} stores
            JOIN {_qualified(schema, "memberships")} memberships
                ON memberships.organization_id = stores.organization_id
            JOIN {_qualified(schema, "users")} users
                ON users.id = memberships.user_id
            WHERE users.email NOT LIKE (
                'owner-' || right(stores.organization_id, 1) || chr(37)
            )
        """,
    }
    for label, query in cross_tenant_checks.items():
        mismatches = _scalar(cursor, query)
        if mismatches != 0:
            raise RuntimeError(f"Restored tenant boundary failed for {label}: {mismatches}")


def main() -> int:
    database_url = os.getenv("VERIFY_POSTGRES_URL", "").replace(
        "postgresql+psycopg://", "postgresql://", 1
    )
    if not database_url:
        raise RuntimeError("VERIFY_POSTGRES_URL is required")
    migration_head = os.getenv("EXPECTED_MIGRATION_HEAD", "20260902_0030")
    pg_dump = shutil.which("pg_dump")
    pg_restore = shutil.which("pg_restore")
    if not pg_dump or not pg_restore:
        raise RuntimeError("PostgreSQL client tools pg_dump and pg_restore are required")
    schema = f"verify_backup_{secrets.token_hex(6)}"
    with tempfile.TemporaryDirectory() as directory:
        archive = Path(directory) / "verification.dump"
        with (
            psycopg.connect(database_url, autocommit=True) as connection,
            connection.cursor() as cursor,
        ):
            create_fixture(cursor, schema, migration_head)
        try:
            subprocess.run(
                [
                    pg_dump,
                    database_url,
                    "--format=custom",
                    "--no-owner",
                    "--no-acl",
                    f"--schema={schema}",
                    f"--file={archive}",
                ],
                check=True,
            )
            with (
                psycopg.connect(database_url, autocommit=True) as connection,
                connection.cursor() as cursor,
            ):
                cursor.execute(f"DROP SCHEMA {_quoted_schema(schema)} CASCADE")
            subprocess.run(
                [
                    pg_restore,
                    f"--dbname={database_url}",
                    "--no-owner",
                    "--no-acl",
                    str(archive),
                ],
                check=True,
            )
            with (
                psycopg.connect(database_url) as connection,
                connection.cursor() as cursor,
            ):
                validate_restored_fixture(cursor, schema, migration_head)
        finally:
            with (
                psycopg.connect(database_url, autocommit=True) as connection,
                connection.cursor() as cursor,
            ):
                cursor.execute(f"DROP SCHEMA IF EXISTS {_quoted_schema(schema)} CASCADE")
    print("PostgreSQL backup/restore commerce drill passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
