def _quoted_schema(schema: str) -> str:
    if not schema.startswith("verify_backup_") or not schema.replace("_", "").isalnum():
        raise ValueError("Unsafe verification schema name")
    return f'"{schema}"'


def _qualified(schema: str, table: str) -> str:
    if table not in CORE_TABLES:
        raise ValueError(f"Unexpected verification table: {table}")
    return f"{_quoted_schema(schema)}.{table}"


def _scalar(cursor: Cursor[Any], query: str, params: tuple[Any, ...] = ()) -> Any:
    cursor.execute(query, params)
    row = cursor.fetchone()
    if row is None:
        raise RuntimeError("Verification query returned no rows")
    return row[0]


